"""Suite driver: run every condition in a suite YAML, aggregate the summaries,
and emit LaTeX-ready table bodies + figure data that drop straight into main.tex.

    python -m gadanplus.run_conditions --suite configs/suite_smoke.yaml

Each suite entry is merged over the suite `defaults`. Outputs land under the
suite `out` dir: per-condition JSONL/summary/manifest/leakage (from run.py) plus
an aggregate `suite_summary.json`, `tables.tex`, and (if matplotlib is present)
figures via figures.py.

INTEGRITY: if ANY condition used the mock backend, every emitted table/figure is
stamped NOT PAPER DATA so reference output can never be mistaken for results.
"""
from __future__ import annotations
import argparse
import json
import os

from . import figures
from .run import run_condition, print_result, _DEFAULT_PREREG

NOT_PAPER = "% ===== NOT PAPER DATA (reference/mock harness) — do not submit ====="


def load_suite(path: str):
    import yaml
    with open(path, encoding="utf-8") as fh:
        suite = yaml.safe_load(fh)
    defaults = suite.get("defaults", {}) or {}
    conditions = []
    for entry in suite.get("conditions", []):
        merged = dict(defaults)
        merged.update(entry)
        conditions.append(merged)
    return suite.get("name", "suite"), suite.get("out", "results/suite"), conditions


# ---- LaTeX emitters --------------------------------------------------------
def _fmt(v, nd=3):
    if v is None:
        return "--"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def adaptive_table(results: list, mock: bool) -> str:
    """tab:adaptive body: the GADA-N+ awareness ladder (A0->A3) x attacker.
    Rows are grouped by attacker then ordered A0->A3."""
    order = {"A0": 0, "A1": 1, "A2": 2, "A3": 3}
    rows = [r for r in results if r["config"]["defence"] == "gadanplus"]
    rows = sorted(rows, key=lambda r: (r["config"]["attacker"],
                                       order.get(r["config"]["awareness"], 9)))
    lines = [NOT_PAPER] if mock else []
    lines += [
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r"Attacker & Aware. & HCR & HCR$_{95}$ & MADT & RCDI & DDR \\",
        r"\midrule",
    ]
    for r in rows:
        c, s = r["config"], r["summary"]
        lines.append(
            f"{c['attacker']} & {c['awareness']} & {_fmt(s['HCR'])} & "
            f"{_fmt(s['HCR_upper95'])} & {_fmt(s['MADT'],1)} & {_fmt(s['RCDI'])} & "
            f"{_fmt(s['DDR'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    if mock:
        lines.append(NOT_PAPER)
    return "\n".join(lines)


def main_table(results: list, mock: bool) -> str:
    """Composite table across DEFENCE conditions at the default awareness (A0),
    i.e. the main-study defence comparison (Table 3 style)."""
    rows = [r for r in results if r["config"]["awareness"] == "A0"]
    rows = sorted(rows, key=lambda r: r["config"]["condition"])
    lines = [NOT_PAPER] if mock else []
    lines += [
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r"Cond. & Defence & HCR & HCR$_{95}$ & MADT & RCDI & $\Delta$QoS \\",
        r"\midrule",
    ]
    for r in rows:
        c, s = r["config"], r["summary"]
        lines.append(
            f"{c['condition']} & {c['defence']} & {_fmt(s['HCR'])} & "
            f"{_fmt(s['HCR_upper95'])} & {_fmt(s['MADT'],1)} & {_fmt(s['RCDI'])} & "
            f"{_fmt(s['dQoS'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    if mock:
        lines.append(NOT_PAPER)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite", required=True, help="path to a suite_*.yaml")
    ap.add_argument("--prereg", default=_DEFAULT_PREREG)
    ap.add_argument("--no-figures", action="store_true")
    args = ap.parse_args()

    name, out_dir, conditions = load_suite(args.suite)
    os.makedirs(out_dir, exist_ok=True)
    print(f"# Suite '{name}': {len(conditions)} conditions -> {out_dir}\n")

    results, any_mock, any_leak = [], False, []
    for cfg in conditions:
        res = run_condition(cfg, out_dir, prereg_path=args.prereg)
        print_result(res)
        print()
        results.append(res)
        any_mock = any_mock or cfg["attacker"] == "mock"
        if res["leak"]["any_leak"] and cfg["attacker"] != "mock":
            any_leak.append(res["tag"])

    # aggregate summary
    agg = {r["tag"]: dict(config=r["config"], summary=r["summary"],
                          leak_any=r["leak"]["any_leak"], leaks=r["leak"]["leaks"])
           for r in results}
    with open(os.path.join(out_dir, "suite_summary.json"), "w", encoding="utf-8") as fh:
        json.dump(dict(name=name, mock=any_mock, results=agg), fh, indent=2)

    # LaTeX tables
    tex = [f"% Suite: {name}  (mock={any_mock})",
           "% Auto-generated by gadanplus.run_conditions — do not hand-edit numbers.",
           "",
           "% --- Composite / defence table (Table 3 style) ---",
           main_table(results, any_mock), "",
           "% --- Adaptive awareness-ladder table (tab:adaptive) ---",
           adaptive_table(results, any_mock), ""]
    tables_path = os.path.join(out_dir, "tables.tex")
    with open(tables_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(tex))

    # figures
    fig_msg = "skipped (--no-figures)"
    if not args.no_figures:
        fig_msg = figures.render_all(results, out_dir, mock=any_mock)

    print("=" * 70)
    print(f"Suite '{name}' complete.")
    print(f"  tables: {tables_path}")
    print(f"  figures: {fig_msg}")
    if any_mock:
        print("  NOTE: mock backend used — all tables/figures are NOT PAPER DATA.")
    if any_leak:
        print(f"  LEAKAGE ERROR on real-backend conditions: {any_leak} "
              f"(do NOT report their DDR/AUROC).")


if __name__ == "__main__":
    main()
